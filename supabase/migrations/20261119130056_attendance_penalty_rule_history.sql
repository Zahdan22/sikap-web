create table if not exists public.attendance_penalty_rule_history (
  id bigint generated by default as identity primary key,
  rule_key text not null check (rule_key ~ '^[a-z0-9_]{3,80}$'),
  label text not null check (char_length(btrim(label)) between 1 and 120),
  rule_kind text not null check (rule_kind in ('late_checkin', 'late_checkout', 'missing_checkin', 'missing_meal')),
  min_minutes integer check (min_minutes is null or min_minutes >= 0),
  max_minutes integer check (max_minutes is null or max_minutes >= min_minutes),
  applies_to text not null default 'all' check (applies_to in ('all', 'senior_plus', 'non_senior_plus')),
  payroll_effect text not null check (payroll_effect in ('deduction', 'unpaid', 'disciplinary')),
  points integer not null check (points >= 0 and points <= 1000000),
  fine numeric not null default 0 check (fine >= 0 and fine <= 100000000),
  is_active boolean not null default true,
  effective_on date not null,
  recorded_by uuid references public.users(id) on delete set null,
  updated_by uuid references public.users(id) on delete set null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique (rule_key, effective_on)
);

create index if not exists attendance_penalty_rule_history_lookup_idx
  on public.attendance_penalty_rule_history (rule_key, effective_on desc, id desc);

alter table public.attendance_penalty_rule_history enable row level security;
