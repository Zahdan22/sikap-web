begin;

-- Allow full jobdesk abbreviations, including comma-separated text.
alter table public.jobdesk alter column singkatan type text;

create table if not exists public.jobdesk_preset (
  id bigint generated by default as identity primary key,
  nama text not null check (length(trim(nama)) > 0),
  dibuat_oleh uuid not null references public.users(id) on delete restrict,
  updated_at timestamptz not null default now()
);
create table if not exists public.jobdesk_preset_item (
  preset_id bigint not null references public.jobdesk_preset(id) on delete cascade,
  jobdesk_id bigint not null references public.jobdesk(id) on delete cascade,
  urutan integer not null check (urutan >= 0),
  primary key(preset_id, jobdesk_id),
  unique(preset_id, urutan)
);
create index if not exists jobdesk_preset_item_jobdesk_idx on public.jobdesk_preset_item(jobdesk_id);
alter table public.jobdesk_preset enable row level security;
alter table public.jobdesk_preset_item enable row level security;
revoke all on public.jobdesk_preset, public.jobdesk_preset_item from anon, authenticated;
grant select, delete on public.jobdesk_preset to authenticated;
grant select on public.jobdesk_preset_item to authenticated;

drop policy if exists "Managers read jobdesk presets" on public.jobdesk_preset;
create policy "Managers read jobdesk presets" on public.jobdesk_preset for select to authenticated
using (exists (select 1 from public.users where id=auth.uid() and role='manager' and status_aktif));
drop policy if exists "Managers delete jobdesk presets" on public.jobdesk_preset;
create policy "Managers delete jobdesk presets" on public.jobdesk_preset for delete to authenticated
using (exists (select 1 from public.users where id=auth.uid() and role='manager' and status_aktif));
drop policy if exists "Managers read jobdesk preset items" on public.jobdesk_preset_item;
create policy "Managers read jobdesk preset items" on public.jobdesk_preset_item for select to authenticated
using (exists (select 1 from public.users where id=auth.uid() and role='manager' and status_aktif));

-- Save the name and membership atomically. Applied schedules store jobdesk IDs
-- independently, so editing or deleting a preset does not rewrite past schedules.
create or replace function public.save_jobdesk_preset(p_id bigint, p_nama text, p_jobdesk_ids bigint[])
returns bigint language plpgsql security definer set search_path=public as $$
declare v_id bigint;
begin
  if not exists (select 1 from public.users where id=auth.uid() and role='manager' and status_aktif) then
    raise exception 'Hanya manager penjadwalan aktif yang dapat mengatur preset jobdesk.';
  end if;
  if p_nama is null or length(trim(p_nama))=0 then raise exception 'Nama preset wajib diisi.'; end if;
  if p_jobdesk_ids is null or cardinality(p_jobdesk_ids) not between 1 and 5 then
    raise exception 'Pilih 1–5 jobdesk untuk satu sel jadwal.';
  end if;
  if (select count(distinct id) from unnest(p_jobdesk_ids) as ids(id)) <> cardinality(p_jobdesk_ids)
    or (select count(*) from public.jobdesk where id=any(p_jobdesk_ids)) <> cardinality(p_jobdesk_ids) then
    raise exception 'Pilihan jobdesk tidak valid atau berulang. Muat ulang daftar.';
  end if;
  if p_id is null then
    insert into public.jobdesk_preset(nama,dibuat_oleh) values(trim(p_nama),auth.uid()) returning id into v_id;
  else
    update public.jobdesk_preset set nama=trim(p_nama), updated_at=clock_timestamp() where id=p_id returning id into v_id;
    if not found then raise exception 'Preset tidak ditemukan. Muat ulang daftar.'; end if;
    delete from public.jobdesk_preset_item where preset_id=v_id;
  end if;
  insert into public.jobdesk_preset_item(preset_id,jobdesk_id,urutan)
  select v_id,id,(position-1)::integer from unnest(p_jobdesk_ids) with ordinality as ids(id,position);
  return v_id;
end;
$$;
revoke all on function public.save_jobdesk_preset(bigint,text,bigint[]) from public,anon;
grant execute on function public.save_jobdesk_preset(bigint,text,bigint[]) to authenticated;
notify pgrst, 'reload schema';
commit;
