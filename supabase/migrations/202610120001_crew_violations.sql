-- Jalankan seluruh file di Supabase SQL Editor setelah migrasi payroll dan lembur.
-- Crew membuat laporan tanpa poin/denda; manager dan finance memeriksa laporan.
-- Denda yang telah diperiksa dihitung oleh aplikasi sesuai tanggal kejadian.
begin;

create table if not exists public.crew_violations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete restrict,
  tanggal date not null,
  kesalahan text not null check (length(trim(kesalahan)) > 0),
  poin integer not null default 0 check (poin >= 0),
  denda numeric(12,0) not null default 0 check (denda >= 0),
  created_by uuid not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  reviewed_by uuid references public.users(id) on delete restrict,
  reviewed_at timestamptz,
  updated_at timestamptz not null default now(),
  version integer not null default 1,
  deleted_by uuid references public.users(id) on delete restrict,
  deleted_at timestamptz,
  check ((reviewed_at is null and reviewed_by is null and poin = 0 and denda = 0)
    or (reviewed_at is not null and reviewed_by is not null))
);
create index if not exists crew_violations_date_user_idx on public.crew_violations(tanggal,user_id) where deleted_at is null;
alter table public.crew_violations enable row level security;
revoke all on public.crew_violations from anon, authenticated;
grant select on public.crew_violations to authenticated;

create or replace function public.is_violation_staff()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.users where id=auth.uid() and status_aktif and role in ('crew','manager','finance'));
$$;
revoke all on function public.is_violation_staff() from public,anon;
grant execute on function public.is_violation_staff() to authenticated;
drop policy if exists "Staff read shared violation register" on public.crew_violations;
create policy "Staff read shared violation register" on public.crew_violations for select to authenticated
using (deleted_at is null and public.is_violation_staff());
grant select on public.periode_kerja to authenticated;
drop policy if exists "Staff read violation work periods" on public.periode_kerja;
create policy "Staff read violation work periods" on public.periode_kerja for select to authenticated using(public.is_violation_staff());

-- Expose only the crew directory fields needed by the shared register.
create or replace function public.violation_crew_directory()
returns table(id uuid,nama text,username text) language plpgsql security definer set search_path=public as $$
begin
  if not public.is_violation_staff() then raise exception 'Akses tidak diizinkan.'; end if;
  return query select u.id,u.nama::text,u.username::text from public.users u where u.role='crew' order by u.nama;
end;
$$;

create or replace function public.save_crew_violation(
  p_id bigint, p_user_id uuid, p_tanggal date, p_kesalahan text,
  p_poin integer default null, p_denda numeric default null, p_version integer default null
) returns bigint language plpgsql security definer set search_path=public as $$
declare
  v_role text;
  v_manager boolean;
  v_old public.crew_violations%rowtype;
  v_id bigint;
begin
  select role into v_role from public.users where id=auth.uid() and status_aktif;
  if v_role is null or v_role not in ('crew','manager','finance') then raise exception 'Akses tidak diizinkan.'; end if;
  v_manager := v_role in ('manager','finance');
  if not v_manager and (p_id is not null or p_user_id is distinct from auth.uid() or p_poin is not null or p_denda is not null) then
    raise exception 'Crew hanya dapat melaporkan kesalahannya sendiri tanpa mengisi poin atau denda.';
  end if;
  if p_tanggal is null or p_tanggal > (now() at time zone 'Asia/Jakarta')::date or p_kesalahan is null or length(trim(p_kesalahan))=0 then
    raise exception 'Isi tanggal kejadian yang valid dan keterangan kesalahan.';
  end if;
  if not exists(select 1 from public.users where id=p_user_id and role='crew') then raise exception 'Crew tidak ditemukan.'; end if;
  if v_manager and (p_poin is null or p_poin<0 or p_denda is null or p_denda<0 or p_denda>=1000000000000 or p_denda<>trunc(p_denda)) then
    raise exception 'Poin dan denda harus berupa angka bulat nol atau lebih.';
  end if;
  -- Same lock as overtime approval and payroll finalization.
  perform pg_advisory_xact_lock(20261011,1);
  if p_id is not null then
    select * into v_old from public.crew_violations where id=p_id and deleted_at is null for update;
    if not found then raise exception 'Laporan pelanggaran tidak ditemukan.'; end if;
    if p_version is distinct from v_old.version then raise exception 'Laporan sudah diubah manager lain. Muat ulang sebelum menyimpan.'; end if;
  end if;
  if exists(select 1 from public.payroll_periods where status='finalized'
    and (p_tanggal between period_start and period_end or v_old.tanggal between period_start and period_end)) then
    raise exception 'Payroll tanggal ini sudah difinalisasi. Laporan pelanggaran tidak dapat diubah.';
  end if;
  if p_id is null then
    insert into public.crew_violations(user_id,tanggal,kesalahan,poin,denda,created_by,reviewed_by,reviewed_at)
    values(p_user_id,p_tanggal,trim(p_kesalahan),coalesce(p_poin,0),coalesce(p_denda,0),auth.uid(),
      case when v_manager then auth.uid() end, case when v_manager then clock_timestamp() end) returning id into v_id;
  else
    update public.crew_violations set user_id=p_user_id,tanggal=p_tanggal,kesalahan=trim(p_kesalahan),poin=p_poin,denda=p_denda,
      reviewed_by=auth.uid(),reviewed_at=clock_timestamp(),updated_at=clock_timestamp(),version=version+1 where id=p_id returning id into v_id;
  end if;
  return v_id;
end;
$$;

create or replace function public.delete_crew_violation(p_id bigint,p_version integer)
returns void language plpgsql security definer set search_path=public as $$
declare v_old public.crew_violations%rowtype;
begin
  if not exists(select 1 from public.users where id=auth.uid() and status_aktif and role in ('manager','finance')) then raise exception 'Akses khusus manager.'; end if;
  perform pg_advisory_xact_lock(20261011,1);
  select * into v_old from public.crew_violations where id=p_id and deleted_at is null for update;
  if not found then raise exception 'Laporan pelanggaran tidak ditemukan.'; end if;
  if p_version is distinct from v_old.version then raise exception 'Laporan sudah diubah manager lain. Muat ulang dahulu.'; end if;
  if exists(select 1 from public.payroll_periods where status='finalized' and v_old.tanggal between period_start and period_end) then
    raise exception 'Payroll sudah difinalisasi. Laporan pelanggaran tidak dapat dihapus.';
  end if;
  update public.crew_violations set deleted_at=clock_timestamp(),deleted_by=auth.uid(),version=version+1 where id=p_id;
end;
$$;

-- Require a fresh draft when a manager changes fines, points, or reviewed rows.
create or replace function public.guard_payroll_violation_finalization()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.status='finalized' and (tg_op='INSERT' or old.status<>'finalized') then
    perform pg_advisory_xact_lock(20261011,1);
    if exists(
      select 1 from (
        select user_id,sum(denda) as amount,sum(poin) as points,count(*) as entries,
          jsonb_agg(jsonb_build_array(id,version) order by id) as revisions from public.crew_violations
        where deleted_at is null and reviewed_at is not null and tanggal between new.period_start and new.period_end group by user_id
      ) v full join (
        select user_id,coalesce((calculation_snapshot->>'violation_deductions')::numeric,0) as amount,
          coalesce((calculation_snapshot->>'violation_points')::numeric,0) as points,
          coalesce(jsonb_array_length(calculation_snapshot->'violation_details'),0) as entries,
          (select jsonb_agg(jsonb_build_array((entry->>'id')::bigint,(entry->>'version')::integer) order by (entry->>'id')::bigint)
           from jsonb_array_elements(calculation_snapshot->'violation_details') entry) as revisions
        from public.payroll_items where payroll_period_id=new.id
      ) i using(user_id)
      where coalesce(v.amount,0)<>coalesce(i.amount,0) or coalesce(v.points,0)<>coalesce(i.points,0) or coalesce(v.entries,0)<>coalesce(i.entries,0)
        or coalesce(v.revisions,'[]'::jsonb)<>coalesce(i.revisions,'[]'::jsonb)
    ) then raise exception 'Data pelanggaran berubah. Simpan ulang draf payroll sebelum finalisasi.'; end if;
  end if;
  return new;
end;
$$;
drop trigger if exists payroll_violation_finalization on public.payroll_periods;
create trigger payroll_violation_finalization before insert or update on public.payroll_periods
for each row execute function public.guard_payroll_violation_finalization();

revoke all on function public.violation_crew_directory() from public,anon;
revoke all on function public.save_crew_violation(bigint,uuid,date,text,integer,numeric,integer) from public,anon;
revoke all on function public.delete_crew_violation(bigint,integer) from public,anon;
revoke all on function public.guard_payroll_violation_finalization() from public,anon,authenticated;
grant execute on function public.violation_crew_directory() to authenticated;
grant execute on function public.save_crew_violation(bigint,uuid,date,text,integer,numeric,integer) to authenticated;
grant execute on function public.delete_crew_violation(bigint,integer) to authenticated;
notify pgrst,'reload schema';
commit;
