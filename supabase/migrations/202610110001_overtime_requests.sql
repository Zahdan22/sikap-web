begin;

-- Run after the existing payroll migrations. Dates use the start of overtime
-- in Asia/Jakarta; an end time before the start time means the following day.
create table if not exists public.overtime_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete restrict,
  tanggal date not null,
  jam_mulai time not null,
  jam_selesai time not null,
  start_at timestamp generated always as (tanggal + jam_mulai) stored,
  end_at timestamp generated always as (
    tanggal + jam_selesai + case when jam_selesai < jam_mulai then interval '1 day' else interval '0 day' end
  ) stored,
  durasi_menit integer generated always as (
    (extract(epoch from (jam_selesai - jam_mulai + case when jam_selesai < jam_mulai then interval '1 day' else interval '0 day' end)) / 60)::integer
  ) stored,
  jam_dibayar integer generated always as (
    floor(extract(epoch from (jam_selesai - jam_mulai + case when jam_selesai < jam_mulai then interval '1 day' else interval '0 day' end)) / 3600)::integer
  ) stored,
  nominal integer generated always as (
    floor(extract(epoch from (jam_selesai - jam_mulai + case when jam_selesai < jam_mulai then interval '1 day' else interval '0 day' end)) / 3600)::integer * 8000
  ) stored,
  keterangan text not null check (length(trim(keterangan)) between 1 and 1000),
  status text not null default 'pending' check (status in ('pending', 'disetujui', 'ditolak')),
  reviewed_by uuid references public.users(id) on delete restrict,
  reviewed_at timestamptz,
  catatan_manajer text check (length(catatan_manajer) <= 1000),
  created_at timestamptz not null default now(),
  check (durasi_menit >= 60 and jam_mulai <> jam_selesai),
  check (extract(second from jam_mulai) = 0 and extract(second from jam_selesai) = 0),
  check ((status = 'pending' and reviewed_by is null and reviewed_at is null)
    or (status <> 'pending' and reviewed_by is not null and reviewed_at is not null))
);

create index if not exists overtime_requests_user_date_idx on public.overtime_requests(user_id, tanggal);
create index if not exists overtime_requests_status_date_idx on public.overtime_requests(status, tanggal);

alter table public.overtime_requests enable row level security;
revoke all on public.overtime_requests from anon, authenticated;
grant select on public.overtime_requests to authenticated;
drop policy if exists "Read own overtime or manage overtime" on public.overtime_requests;
create policy "Read own overtime or manage overtime" on public.overtime_requests
for select to authenticated using (
  exists (select 1 from public.users u where u.id = auth.uid() and u.status_aktif
    and (u.role in ('manager', 'finance') or (u.role = 'crew' and user_id = u.id)))
);

-- All writes go through authenticated RPCs. The shared transaction lock also
-- serializes approvals against payroll finalization and overlapping submissions.
create or replace function public.submit_overtime_request(
  p_tanggal date, p_jam_mulai time, p_jam_selesai time, p_keterangan text
) returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_user uuid := auth.uid();
  v_start timestamp;
  v_end timestamp;
  v_id bigint;
begin
  if not exists (select 1 from public.users where id = v_user and role = 'crew' and status_aktif) then
    raise exception 'Hanya crew aktif yang dapat mengajukan lembur.';
  end if;
  if p_tanggal is null or p_jam_mulai is null or p_jam_selesai is null
    or p_keterangan is null or length(trim(p_keterangan)) not between 1 and 1000
    or extract(second from p_jam_mulai) <> 0 or extract(second from p_jam_selesai) <> 0 then
    raise exception 'Lengkapi tanggal, jam, dan keterangan lembur yang valid.';
  end if;
  v_start := p_tanggal + p_jam_mulai;
  v_end := p_tanggal + p_jam_selesai + case when p_jam_selesai < p_jam_mulai then interval '1 day' else interval '0 day' end;
  if v_end - v_start < interval '1 hour' then
    raise exception 'Lembur kurang dari 1 jam. Minimal lembur 1 jam.';
  end if;
  perform pg_advisory_xact_lock(20261011, 1);
  if exists (select 1 from public.payroll_periods where status = 'finalized' and p_tanggal between period_start and period_end) then
    raise exception 'Payroll tanggal ini sudah difinalisasi. Pengajuan lembur tidak dapat ditambahkan.';
  end if;
  if exists (select 1 from public.overtime_requests where user_id = v_user and status in ('pending', 'disetujui')
    and start_at < v_end and end_at > v_start) then
    raise exception 'Rentang waktu ini bertabrakan dengan pengajuan lembur yang menunggu atau sudah disetujui.';
  end if;
  insert into public.overtime_requests(user_id, tanggal, jam_mulai, jam_selesai, keterangan)
  values (v_user, p_tanggal, p_jam_mulai, p_jam_selesai, trim(p_keterangan)) returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.review_overtime_request(p_id bigint, p_status text, p_catatan text default '')
returns void language plpgsql security definer set search_path = public as $$
declare
  v_request public.overtime_requests%rowtype;
begin
  if not exists (select 1 from public.users where id = auth.uid() and role in ('manager', 'finance') and status_aktif) then
    raise exception 'Hanya manager aktif yang dapat memproses pengajuan lembur.';
  end if;
  if p_status is null or p_status not in ('disetujui', 'ditolak') or length(coalesce(p_catatan, '')) > 1000 then
    raise exception 'Keputusan atau catatan manager tidak valid.';
  end if;
  perform pg_advisory_xact_lock(20261011, 1);
  select * into v_request from public.overtime_requests where id = p_id for update;
  if not found then raise exception 'Pengajuan lembur tidak ditemukan.'; end if;
  if v_request.status <> 'pending' then raise exception 'Pengajuan lembur sudah diproses oleh manager lain. Muat ulang daftar.'; end if;
  if p_status = 'disetujui' and exists (
    select 1 from public.payroll_periods where status = 'finalized' and v_request.tanggal between period_start and period_end
  ) then raise exception 'Payroll tanggal ini sudah difinalisasi. Lembur tidak dapat disetujui.'; end if;
  update public.overtime_requests set status = p_status, reviewed_by = auth.uid(), reviewed_at = now(),
    catatan_manajer = nullif(trim(coalesce(p_catatan, '')), '') where id = p_id;
end;
$$;

-- Refuse finalization if overtime was approved after the last saved draft.
create or replace function public.guard_payroll_overtime_finalization()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'finalized' and (tg_op = 'INSERT' or old.status <> 'finalized') then
    perform pg_advisory_xact_lock(20261011, 1);
    if exists (
      select 1 from (
        select user_id, sum(nominal) as amount from public.overtime_requests
        where status = 'disetujui' and tanggal between new.period_start and new.period_end group by user_id
      ) o full join (
        select user_id, coalesce((calculation_snapshot->>'overtime_pay')::numeric, 0) as amount
        from public.payroll_items where payroll_period_id = new.id
      ) i using (user_id)
      where coalesce(o.amount, 0) <> coalesce(i.amount, 0)
    ) then raise exception 'Data lembur berubah. Simpan ulang draf payroll sebelum finalisasi.'; end if;
  end if;
  return new;
end;
$$;
drop trigger if exists payroll_overtime_finalization on public.payroll_periods;
create trigger payroll_overtime_finalization before insert or update on public.payroll_periods
for each row execute function public.guard_payroll_overtime_finalization();

-- A draft save that started before finalization must not overwrite the locked
-- overtime snapshot after finalization commits.
create or replace function public.guard_finalized_payroll_items()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(20261011, 1);
  if tg_op <> 'INSERT' then
    if exists (select 1 from public.payroll_periods where id = old.payroll_period_id and status = 'finalized') then
      raise exception 'Payroll sudah difinalisasi. Rekap tidak dapat diubah.';
    end if;
  end if;
  if tg_op <> 'DELETE' then
    if exists (select 1 from public.payroll_periods where id = new.payroll_period_id and status = 'finalized') then
      raise exception 'Payroll sudah difinalisasi. Rekap tidak dapat diubah.';
    end if;
    return new;
  end if;
  return old;
end;
$$;
drop trigger if exists finalized_payroll_items_guard on public.payroll_items;
create trigger finalized_payroll_items_guard before insert or update or delete on public.payroll_items
for each row execute function public.guard_finalized_payroll_items();

revoke all on function public.submit_overtime_request(date, time, time, text) from public, anon;
revoke all on function public.review_overtime_request(bigint, text, text) from public, anon;
revoke all on function public.guard_payroll_overtime_finalization() from public, anon, authenticated;
revoke all on function public.guard_finalized_payroll_items() from public, anon, authenticated;
grant execute on function public.submit_overtime_request(date, time, time, text) to authenticated;
grant execute on function public.review_overtime_request(bigint, text, text) to authenticated;
notify pgrst, 'reload schema';
commit;
